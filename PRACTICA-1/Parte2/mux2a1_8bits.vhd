ENTITY mux2a1_8bits IS
PORT(SIGNAL SW: IN BIT_VECTOR(17 DOWNTO 0);
	  SIGNAL LEDG: OUT BIT_VECTOR(7 DOWNTO 0);
	  SIGNAL LEDR: OUT BIT_VECTOR(17 DOWNTO 0)
);
END mux2a1_8bits;

ARCHITECTURE X OF mux2a1_8bits IS
COMPONENT mux2a1 IS
port(SIGNAL X, Y: IN BIT_VECTOR(7 DOWNTO 0); -- ENTRADA DE X,Y
	  SIGNAL S:IN BIT; --SELECTOR
	  SIGNAL M: OUT BIT_VECTOR(7 DOWNTO 0));--SALIDA M DEL MUX  
END COMPONENT;
BEGIN
conexion1: mux2a1 PORT MAP(SW(7 DOWNTO 0), SW(15 DOWNTO 8), SW(17), LEDG);
LEDR <= SW; -- Para reflejar las entradas en los leds rojos
END X;