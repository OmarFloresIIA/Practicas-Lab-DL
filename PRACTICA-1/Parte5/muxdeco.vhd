ENTITY muxdeco IS
 PORT(SIGNAL S, U, V, W, X, Y: IN BIT_VECTOR(2 DOWNTO 0);
		SIGNAL DISPLAY: OUT BIT_VECTOR(6 DOWNTO 0));
END muxdeco;

ARCHITECTURE X OF muxdeco IS
-- Componente decoder
COMPONENT decoder IS
 PORT(SIGNAL SW: IN BIT_VECTOR(2 DOWNTO 0);
		SIGNAL HEX0: OUT BIT_VECTOR(6 DOWNTO 0));
END COMPONENT;
--Componente mux5a1_3bits
COMPONENT mux5a1de3bits IS
PORT(SIGNAL S, U, V, W, X, Y: IN BIT_VECTOR(2 DOWNTO 0);
	  SIGNAL M: OUT BIT_VECTOR(2 DOWNTO 0));
END COMPONENT;
SIGNAL Ms: BIT_VECTOR(2 DOWNTO 0);
BEGIN
conexion1: mux5a1de3bits PORT MAP(S, U, V, W, X, Y, Ms);
conexion2: decoder PORT MAP(Ms, DISPLAY);
END X;
